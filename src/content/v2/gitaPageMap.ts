import type { GitaMappingStatus } from './gitaDocument';

/**
 * Bhagavad Gītā canonical↔KSTS source backbone (Phase 2).
 *
 * One row per canonical unit: its KSTS reference(s), verified PDF page
 * and printed folio, explicitly printed speaker (null = the edition
 * prints no label, normal mid-run — never an unknown speaker), and a
 * mapping status. Generated from the inspected file
 * (`Gitasarvatobhadrarajanka.pdf`) by deterministic verse-marker
 * extraction with running-head validation; anomalies were resolved by
 * direct page inspection. Method and per-chapter findings:
 * `docs/scholarly/bhagavad-gita-sarvatobhadra-architecture.md`.
 *
 * KSTS extras (numbered verses with no canonical counterpart) and the
 * thirteen adhika appendix units travel in the same module so future
 * concepts, threads and the reader share one lookup.
 */

export interface GitaUnitMapRow {
  /** KSTS references, fully qualified (`2.12`); spans list each number. */
  ksts: string[];
  /** PDF page of the verse text in the inspected file. */
  pdf?: number;
  /** Printed folio (PDF page minus ten). */
  folio?: number;
  /** Speaker label exactly as printed (Devanāgarī spelling kept). */
  speaker?: string;
  status: GitaMappingStatus;
  note?: string;
}

