/** Backbone row for any Gītā unit id (mūla or adhika); undefined otherwise. */
export function gitaMapForUnit(unitId: string): GitaUnitMapRow | undefined {
  return GITA_UNIT_MAP[unitId] || GITA_ADHIKA_MAP[unitId];
}

/**
 * Display-ready KSTS source number for a unit: bare number where the
 * chapter matches (`12`), fully qualified across chapters (`6.10`),
 * hyphenated for spans (`78-79`). Undefined when the unit has no KSTS
 * counterpart at all.
 */
export function gitaSourceNumber(unitId: string): string | undefined {
  const row = gitaMapForUnit(unitId);
  if (!row || row.ksts.length === 0) return undefined;
  const chapter = unitId.startsWith('adhika.') ? null : unitId.split('.')[0];
  const nums = row.ksts.map((k) => (chapter && k.startsWith(`${chapter}.`) ? k.slice(chapter.length + 1) : k));
  if (nums.length === 1) return nums[0];
  const first = nums[0].split('.')[1] || nums[0];
  const last = nums[nums.length - 1].split('.').pop() || nums[nums.length - 1];
  const ch = nums[0].includes('.') ? `${nums[0].split('.')[0]}.` : '';
  return `${ch}${first}-${last}`;
}
